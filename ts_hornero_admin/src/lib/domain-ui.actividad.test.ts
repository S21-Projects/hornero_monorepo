import { describe, it, expect } from 'vitest';
import { ACCION_ACTIVIDAD, labelAccion } from './domain-ui';

// Mirrors the MS `TipoActividad` enum. A new MS value without a label here would still render
// (raw code), but this list keeps the Spanish copy complete.
const MS_TIPOS = [
  'LOGIN', 'LOGOUT', 'REGISTRO', 'REFRESH_TOKEN', 'REFRESH_TOKEN_REUTILIZADO', 'OTP_VERIFICACION',
  'OTP_BLOQUEO', 'ENTREGA_CODIGO_GENERADO', 'ENTREGA_CODIGO_VERIFICACION', 'ENTREGA_CODIGO_BLOQUEO',
  'USUARIO_ACTIVADO', 'USUARIO_DESACTIVADO', 'ORGANIZACION_CREADA', 'ORGANIZACION_VALIDADA',
  'ORGANIZACION_RECHAZADA', 'ORGANIZACION_ACTUALIZADA', 'ORGANIZACION_REFERENTE_REASIGNADO',
  'ORGANIZACION_INFO_PUBLICA_EDITADA', 'ORGANIZACION_INFO_PUBLICA_APROBADA',
  'ORGANIZACION_INFO_PUBLICA_RECHAZADA', 'RECLAMO_CREADO', 'RECLAMO_APROBADO',
  'RECLAMO_RECHAZADO', 'REPORTE_CREADO', 'REPORTE_CONFIRMADO', 'REPORTE_DESCARTADO', 'NECESIDAD_CREADA', 'NECESIDAD_ACTUALIZADA',
  'NECESIDAD_ELIMINADA', 'NECESIDAD_RELANZADA', 'NECESIDADES_VENCIDAS', 'DONACION_CREADA',
  'DONACION_DECISION', 'DONACION_ESTADO_ACTUALIZADO', 'DONACION_CANCELADA', 'DONACION_ELIMINADA',
  'DONACION_OVERRIDE', 'RONDA_EJECUTADA', 'ARTICULO_CREADO', 'ARTICULO_ACTUALIZADO',
  'ARTICULO_DESACTIVADO', 'ARTICULO_REACTIVADO', 'TOKENS_PURGADOS', 'ACTIVIDAD_PURGADA',
  'USUARIO_ANONIMIZADO', 'EMAIL_INTENTO_PURGADO', 'COORDENADAS_MINIMIZADAS',
];

describe('ACCION_ACTIVIDAD', () => {
  it('has a Spanish label for every MS TipoActividad', () => {
    for (const tipo of MS_TIPOS) {
      expect(ACCION_ACTIVIDAD[tipo], tipo).toBeTruthy();
    }
    expect(Object.keys(ACCION_ACTIVIDAD).sort()).toEqual([...MS_TIPOS].sort());
  });

  it('labelAccion falls back to the raw code', () => {
    expect(labelAccion('LOGIN')).toBe('Inicio de sesión');
    expect(labelAccion('NUEVA')).toBe('NUEVA');
  });
});
